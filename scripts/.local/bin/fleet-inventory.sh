#!/bin/bash
# fleet-inventory.sh — enumerate every VM/CT on the Proxmox cluster and
# regenerate ~/.ssh/config.d/fleet so `ssh <name>` (or `fleet ssh <name>`)
# reaches any of them, including ones created after this script last ran.
#
# IP resolution order per guest:
#   1. QEMU guest agent (if installed and running) — most reliable.
#   2. ARP: ping the guest's known MAC-adjacent subnet, then match the
#      configured NIC MAC against the Proxmox host's ARP table. Works even
#      without the guest agent, as long as the guest is on the same L2 as
#      the Proxmox host's bridge.
#
# Run manually, or via the fleet-inventory.timer systemd unit.

set -euo pipefail

CRED_FILE="$HOME/.config/fleet/api-token.env"
SSH_KEY="$HOME/.ssh/ai_fleet_ed25519"
CONFIG_D="$HOME/.ssh/config.d"
FLEET_CONFIG="$CONFIG_D/fleet"
FLEET_JSON="$HOME/.config/fleet/inventory.json"

if [ ! -f "$CRED_FILE" ]; then
  echo "fleet-inventory: missing $CRED_FILE" >&2
  exit 1
fi
# shellcheck disable=SC1090
source "$CRED_FILE"

AUTH_HEADER="Authorization: PVEAPIToken=${PVE_API_TOKEN_ID}=${PVE_API_TOKEN_SECRET}"
API="https://${PVE_API_HOST}:8006/api2/json"

mkdir -p "$CONFIG_D" "$(dirname "$FLEET_JSON")"

resources=$(curl -sk -H "$AUTH_HEADER" "$API/cluster/resources" | jq -c '.data[] | select(.type=="qemu" or .type=="lxc")')

# Refresh the Proxmox host's ARP cache for the whole /24 once, up front,
# so MAC lookups below don't each pay a ping round-trip.
subnet=$(echo "$PVE_API_HOST" | awk -F. '{print $1"."$2"."$3}')
ssh -o BatchMode=yes -o ConnectTimeout=5 "root@${PVE_API_HOST}" \
  "for i in \$(seq 1 254); do ping -c1 -W1 ${subnet}.\$i >/dev/null 2>&1 & done; wait" || true
arp_table=$(ssh -o BatchMode=yes -o ConnectTimeout=5 "root@${PVE_API_HOST}" "ip neigh show" || true)

fleet_entries=()
json_entries=()

while IFS= read -r r; do
  [ -z "$r" ] && continue
  vmid=$(echo "$r" | jq -r '.vmid')
  node=$(echo "$r" | jq -r '.node')
  type=$(echo "$r" | jq -r '.type')
  name=$(echo "$r" | jq -r '.name')
  status=$(echo "$r" | jq -r '.status')
  template=$(echo "$r" | jq -r '.template')

  [ "$template" = "1" ] && continue   # skip templates, they're not reachable guests
  [ "$status" != "running" ] && continue

  guest_type_path="qemu"
  [ "$type" = "lxc" ] && guest_type_path="lxc"

  ip=""
  # 1. Try guest agent (qemu only)
  if [ "$type" = "qemu" ]; then
    agent_resp=$(curl -sk -H "$AUTH_HEADER" "$API/nodes/$node/qemu/$vmid/agent/network-get-interfaces" 2>/dev/null || true)
    ip=$( { echo "$agent_resp" | jq -r '.data.result[]?.["ip-addresses"][]? | select(.["ip-address-type"]=="ipv4") | .["ip-address"]' 2>/dev/null | grep -v '^127\.' | head -n1; } || true)
  fi

  # 2. Fallback: match configured MAC against the Proxmox host's ARP table
  if [ -z "$ip" ]; then
    config=$(curl -sk -H "$AUTH_HEADER" "$API/nodes/$node/$guest_type_path/$vmid/config")
    mac=$( { echo "$config" | jq -r '.data.net0 // empty' | grep -oiE '([0-9a-f]{2}:){5}[0-9a-f]{2}' | head -n1; } || true)
    if [ -n "$mac" ]; then
      ip=$( { echo "$arp_table" | grep -i "$mac" | awk '{print $1}' | head -n1; } || true)
    fi
  fi

  if [ -z "$ip" ]; then
    echo "fleet-inventory: could not resolve IP for $type $vmid ($name), skipping" >&2
    continue
  fi

  slug=$(echo "$name" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9' '-' | sed 's/-\+/-/g; s/^-//; s/-$//')
  host_alias="vm-${slug}"

  fleet_entries+=("Host ${host_alias}
  HostName ${ip}
  User ai-agent
  IdentityFile ${SSH_KEY}
  StrictHostKeyChecking accept-new
")

  json_entries+=("$(jq -n --arg name "$name" --arg alias "$host_alias" --arg ip "$ip" \
    --arg vmid "$vmid" --arg type "$type" --arg node "$node" \
    '{name:$name, alias:$alias, ip:$ip, vmid:$vmid, type:$type, node:$node}')")
done <<< "$resources"

{
  echo "# AUTO-GENERATED by fleet-inventory.sh — do not edit by hand."
  echo "# Regenerated: $(date -Iseconds)"
  echo
  for e in "${fleet_entries[@]:-}"; do
    [ -n "$e" ] && echo "$e"
  done
} > "$FLEET_CONFIG"

printf '%s\n' "${json_entries[@]:-}" | jq -s '.' > "$FLEET_JSON"

echo "fleet-inventory: wrote ${#fleet_entries[@]} host(s) to $FLEET_CONFIG"
